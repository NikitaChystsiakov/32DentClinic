import { cn } from '@/lib/utils'

/*
 * Viber-логотип. Раньше здесь был знак, перерисованный в сетке lucide, — он
 * не совпадал с фирменным: у настоящего сплошная трубка и три дуги сигнала,
 * а не тонкая дужка. Теперь это маска по /images/viber-icon.png — он собран
 * из фирменного знака (public/images/viber.png, там же исходник для
 * пересборки): поля обрезаны до 80% бокса, то есть до той же оптической
 * массы, что у соседних lucide-иконок, а обводка слегка утолщена — в
 * оригинале она тоньше lucide-шной (≈1.16px против 1.67px при size-5) и
 * рядом с телеграмом знак читался бы бледнее.
 *
 * Заливка — currentColor, поэтому иконка меняет цвет вместе с текстом ссылки
 * ровно так же, как <Send/> рядом: и в покое, и на ховере, и в тёмной теме.
 * Размер задаётся снаружи через className (size-4 / size-5).
 */
export function ViberIcon({ className }: { className?: string }) {
  return <span aria-hidden className={cn('viber-glyph', className)} />
}
