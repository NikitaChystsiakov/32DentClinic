// Курс для цен в российских рублях на странице медтуризма (/minsk/medturizm/).
// Прайс клиники — в BYN (config/services.ts), рубли — пересчёт для ориентира:
// на странице всегда «≈» и подпись, что оплата — в BYN по курсу на день оплаты.
//
// Для не-разработчика: раз в месяц (или при заметном скачке курса) обновите
// RUB_PER_BYN и RUB_RATE_DATE по официальному курсу Нацбанка РБ —
// https://www.nbrb.by/statistics/rates/ratesdaily → «100 российских рублей».
// RUB_PER_BYN = 100 / курс. Пример: 100 RUB = 3,5964 BYN → 100 / 3,5964 ≈ 27,8.

/** Сколько российских рублей в одном белорусском. НБРБ, 13.10.2026: 100 RUB = 3,5964 BYN. */
export const RUB_PER_BYN = 27.8

/** Дата курса — выводится в подписи под ценами. */
export const RUB_RATE_DATE = '13.10.2026'

/**
 * BYN → «≈ 33 400 ₽». Округление до сотни: точнее курс всё равно не держится,
 * а «33 361 ₽» выглядит как точная цена, которой нет.
 */
export function formatRubFromByn(byn: number): string {
  const rub = Math.round((byn * RUB_PER_BYN) / 100) * 100
  return `≈ ${rub.toLocaleString('ru-RU')} ₽`
}
