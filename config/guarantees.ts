import { hasGuaranteePage } from './guarantee-pages'

export interface GuaranteeRow {
  /** Вид работы — как пациент его назовёт, а не как в приложении. */
  name: string
  /** Уточнение мелким шрифтом: материал, класс полости. */
  note?: string
  /** Гарантийный срок. */
  term: string
  /** Срок службы, если отличается по формулировке от гарантии. */
  serviceLife: string
}

export interface GuaranteeTable {
  title: string
  /** Откуда сроки: «Приложение 1» — чтобы пациент нашёл их в PDF. */
  source: string
  rows: GuaranteeRow[]
  /** Сноска под таблицей. */
  footnote?: string
}

export interface GuaranteePolicy {
  /** Юрлицо, которое утвердило положение. */
  entityName: string
  /** Дата утверждения, ДД.ММ.ГГГГ. */
  approvedAt: string
  /** PDF в public/. */
  pdf: string
  /** Главные цифры — карточки в начале страницы. */
  highlights: { value: string; label: string; description: string }[]
  tables: GuaranteeTable[]
  /** Имплантация: три вида гарантии из раздела 6.3. */
  implants: { title: string; description: string }[]
  /** Ортодонтия (брекеты, каппы): раздел 6.4. */
  orthodontics: string[]
  /** Права пациента в гарантийный срок (раздел 2). */
  rights: string[]
  /** Что нужно делать, чтобы гарантия сохранилась (3.3, 3.4). */
  conditions: string[]
  /** Когда срок сокращается (раздел 5, 6.2.7). */
  reductions: { value: string; label: string }[]
  /** На что гарантия не даётся (раздел 4) — самое частое, не весь список. */
  exclusions: string[]
  /** Обстоятельства, при которых гарантия прекращается (3.4, 4). */
  terminations: string[]
  /** Куда обращаться (раздел 3): телефоны и почта из положения. */
  contacts: { phones: { label: string; href: string }[]; email: string }
}

