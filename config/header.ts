// Компоновка двухполосной шапки. Логотип 32Дент высокий (258×171, ~3:2),
// поэтому высота полос и размер логотипа вынесены в один переключатель —
// поменяйте значение HEADER_LAYOUT, чтобы сравнить варианты вживую:
//
//   'compact'  — самая низкая шапка: логотип 40px, полосы 64 + 48.
//   'balanced' — логотип 56px выровнен по центру верхней полосы, полосы 80 + 52.
//   'anchored' — крупный логотип 88px «свисает» из верхней полосы в нижнюю,
//                навигация начинается правее него. Полосы 68 + 52.
export type HeaderLayout = 'compact' | 'balanced' | 'anchored'

export const HEADER_LAYOUT: HeaderLayout = 'balanced'
