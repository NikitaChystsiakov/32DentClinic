// Раздел «Имплантация» — главное направление сети. Одна запись = один
// протокол (одиночный имплант, All-on-4 …) со своей страницей
// /<город>/uslugi/implantaciya/<slug>/. Хаб /<город>/uslugi/implantaciya/
// собирает карточки отсюда же, как и блок «Виды имплантации» на главной.
//
// Для не-разработчика:
//   • Цены — в `pricing` по каждому городу. `from: null` — цена не
//     фиксируется заранее (All-on-4/6 считают после КТ), на сайте выводится
//     текст из `note`. Цены — из прайса заказчика от 25.09.2026, он общий
//     для всех городов (config/services.ts).
//   • `availableIn` — в каких городах протокол делают. Уберите город из
//     списка, и протокол пропадёт с его страниц.
//   • Тексты не должны обещать результат («приживаемость 99 %», «без
//     боли», «навсегда») и сравнивать клинику с другими — ст. 15 Закона
//     «О рекламе». Пишем про процесс, а не про гарантированный итог.

import type { FaqItem } from './services'
import type { TreatmentTimeline } from '@/content/types'

export type IncludedStatus = 'included' | 'extra' | 'tbd'

export interface IncludedItem {
  name: string
  /** included — входит в цену; extra — оплачивается отдельно; tbd — клиника не подтвердила. */
  status: IncludedStatus
}

export interface ProtocolStep {
  title: string
  duration: string
  description: string
}

export interface ProtocolPricing {
  /** Цена «от» в BYN; null — считается индивидуально, показываем `note`. */
  from: number | null
  /** Подпись под ценой: что именно стоит столько или почему цены нет. */
  note: string
}

export interface ImplantProtocol {
  slug: string
  /** Короткое имя для карточек и меню: «All-on-4». */
  shortName: string
  /** H1 без города — страница сама добавит «в Минске». */
  title: string
  /** Title для поисковиков без названия клиники. */
  metaTitle: string
  cardDescription: string
  intro: string
  /** Имя иконки из lucide-react, см. iconMap в implant-types-section.tsx. */
  icon: string
  /** Бриф на иллюстрацию — пока файла нет, на странице заглушка с этим текстом. */
  imageHint: string
  /** Путь к готовой иллюстрации; пока не задан — показывается заглушка. */
  image?: string
  forWhom: string[]
  included: IncludedItem[]
  steps: ProtocolStep[]
  /** Общий срок от консультации до постоянной коронки одной строкой. */
  durationSummary: string
  pricing: Record<string, ProtocolPricing>
  faq: FaqItem[]
  availableIn: string[]
}

