export function getProtocolBySlug(slug: string) {
  return implantProtocols.find((p) => p.slug === slug)
}

export function getProtocolsForCity(citySlug: string) {
  return implantProtocols.filter((p) => p.availableIn.includes(citySlug))
}

/** Цена протокола для города; для города вне availableIn — undefined. */
export function getProtocolPricing(protocol: ImplantProtocol, citySlug: string): ProtocolPricing | undefined {
  return protocol.pricing[citySlug]
}
