// Страница для пациентов из России: /minsk/medturizm/. Главное действие —
// прислать снимок с сайта; менеджер связывается и называет примерную
// стоимость, дальше человек планирует поездку. Упор — на имплантацию и
// протезирование: ради дорогих и долгих работ едут из другой страны.
//
// Для не-разработчика: тексты страницы — здесь. Цены сюда не пишутся —
// они берутся из прайса (config/services.ts) по названию процедуры и
// пересчитываются в рубли по курсу из config/currency.ts.
//
// [TBD] — допущения первой версии, их нужно подтвердить у клиники:
//   • сроки поездок (сколько дней на первую и вторую поездку);
//   • трансфер и проживание (что клиника реально организует);
//   • гарантия после отъезда — онлайн-контроль и компенсация дороги
//     предложены нами, клиника их ещё не согласовала;
//   • срок ответа менеджера и способы оплаты для россиян.
// Тексты не обещают результат и не сравнивают с другими клиниками
// (ст. 15 Закона «О рекламе»), цены в рублях — ориентир, не оферта.

import type { FaqItem } from '@/config/services'

/**
 * Черновик: страница закрыта от индексации (noindex), её нет в sitemap и
 * на неё не ведут ссылки с сайта, а пункты с `tbd: true` помечены плашкой
 * «согласовать». Так первую версию можно показать клинике по прямой ссылке.
 * Когда тексты и [TBD] согласованы — поставьте false.
 */
export const MEDTOURISM_DRAFT = true

export interface MedTourismReason {
  title: string
  description: string
  /** Имя иконки lucide-react, см. iconMap в components/town/town-reasons.tsx. */
  icon: string
}

/**
 * Карточка цены. Сумма — из прайса: `procedures` — точные названия строк
 * config/services.ts (из любой услуги), цены складываются. Опечатка в
 * названии роняет сборку, а не тихо показывает 0 ₽.
 */
export interface MedTourismPrice {
  title: string
  note: string
  procedures: string[]
  /** Ссылка «подробнее» — страница услуги или протокола внутри города. */
  href: string
}

/** Шаг «как получить расчёт» — до поездки, всё онлайн. */
export interface MedTourismStep {
  title: string
  description: string
}

/** Поездка или пауза между ними в плане лечения. */
export interface MedTourismTripPhase {
  kind: 'trip' | 'pause'
  /** «Поездка 1», «Дома». */
  label: string
  /** «3–5 дней», «3–6 месяцев». */
  duration: string
  title: string
  items: string[]
}

export interface MedTourismPlan {
  /** «Один имплант», «All-on-4 / All-on-6». */
  name: string
  phases: MedTourismTripPhase[]
}

export interface MedTourismCard {
  title: string
  description: string
  icon: string
  /** true — пункт не согласован с клиникой: в разработке видна плашка. */
  tbd?: boolean
}

