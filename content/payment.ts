// Минск: о картах рассрочки и банках договаривалась минская клиника.
//
// Источник: встреча с директором минской клиники 17.11.2026 — «как на
// implant-center.by, но без карты Белгазпромбанка; кредиты оставить все,
// клиника получает полную сумму от банка», плюс блок «Оплата по реквизитам»
// по образцу lode.by. Условия банков — с сайтов банков и implant-center.by
// на 19.11.2026. Банки меняют ставки без предупреждения, поэтому на странице
// везде стоит «уточняйте на сайте банка», а дата сверки — в `checkedAt`.
//
// Для не-разработчика:
//   • Убрать банк или карту — удалите его блок { … } целиком.
//   • Поменять ставку или срок — правьте текст в кавычках.
//   • Реквизиты юрлица берутся из config/cities.ts (legal); здесь —
//     только банковский счёт, его клиника пока не прислала.
//
// Рассрочку в сентябре по просьбе владельца убирали со всего сайта; страница
// появилась по новой договорённости с клиникой (17.11.2026).

import { PAYMENT_PAGE_CITIES } from '@/config/payment-pages'

export interface PaymentMethod {
  icon: string
  title: string
  description: string
  /** Якорь блока на этой же странице, если о способе есть подробности ниже. */
  anchor?: string
}

export interface InstallmentCard {
  name: string
  bank: string
  /** Срок рассрочки — крупной цифрой на карточке. */
  term: string
  termLabel: string
  points: string[]
  href: string
}

export interface CreditOffer {
  name: string
  bank: string
  /** Ключевые условия: подпись + значение. */
  terms: { label: string; value: string }[]
  note?: string
  href: string
}

export interface PaymentFaqItem {
  question: string
  answer: string
}

export interface PaymentContent {
  metaTitle: string
  metaDescription: string
  checkedAt: string
  hero: {
    eyebrow: string
    title: string
    subtitle: string
    facts: { value: string; label: string }[]
  }
  methods: PaymentMethod[]
  installment: {
    title: string
    subtitle: string
    cards: InstallmentCard[]
    steps: { title: string; text: string }[]
  }
  credit: {
    title: string
    subtitle: string
    offers: CreditOffer[]
    steps: { title: string; text: string }[]
  }
  requisites: {
    title: string
    subtitle: string
    /**
     * Банковский счёт для перевода. Пока не задан — вместо него строка
     * «счёт на оплату пришлёт администратор». [TBD] — реквизиты от клиники.
     */
    bankAccount?: { iban: string; bankName: string; bic: string }
  }
  faq: PaymentFaqItem[]
}

