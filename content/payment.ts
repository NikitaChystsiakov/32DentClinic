export function getPaymentContent(citySlug: string): PaymentContent | undefined {
  // Ссылки в меню строятся по PAYMENT_PAGE_CITIES — без контента страница
  // ответила бы 404, поэтому оба списка должны совпадать.
  return PAYMENT_PAGE_CITIES.includes(citySlug) ? paymentContents[citySlug] : undefined
}
