/**
 * Адрес без названия города — для шапки сайта.
 *
 * В конфиге адрес хранится целиком («г. Минск, Пр. Победителей, 41»), потому
 * что в футере, на карте и в разметке организации он нужен полным. Но в шапке
 * рядом стоит переключатель города, который и так показывает «Минск», поэтому
 * город в адресе дублируется — и именно из-за него длинные адреса не влезали
 * в строку и обрезались многоточием.
 *
 * Возвращает «Пр. Победителей, 41». Если адрес начинается не с города,
 * возвращает его как есть — обрезать что-то наугад тут опаснее, чем ничего.
 */
export function formatAddressWithoutCity(address: string): string {
  const withoutCity = address.replace(/^\s*(?:г\.|гор\.|город)\s*[^,]+,\s*/i, '').trim()
  return withoutCity || address
}
